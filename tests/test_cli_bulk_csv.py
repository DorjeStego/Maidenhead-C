@pytest.mark.parametrize(
    "op,lines,extra_args",
    [
        ("center", LOCATORS, None),
        ("bbox", LOCATORS, ["--digits", "6"]),
        ("contains-point", _center_point_lines(LOCATORS), None),
        ("intersects-polygon", _bbox_polygon_lines(LOCATORS), None),
        ("neighbors", LOCATORS, None),
        ("adjacent", LOCATORS, None),
        ("corners", LOCATORS, None),
        ("precision", LOCATORS, None),
        ("parent", LOCATORS, None),
        ("children", LOCATORS, None),
        ("size", LOCATORS, ["--unit", "deg", "--digits", "6"]),
        ("area", LOCATORS, ["--method", "spherical", "--digits", "6"]),
        ("diagonal", LOCATORS, ["--method", "spherical", "--digits", "6"]),
        ("utm", LOCATORS, None),
        ("geojson", LOCATORS, None),
    ],
)
def test_bulk_csv_values(tmp_path, op, lines, extra_args):
    rows = _run_bulk_csv(tmp_path, op, lines, extra_args)
    header = rows[0]
    data = rows[1:]
    tol = 1e-6
    if op == "center":
        assert header == ["input", "lat", "lon"]
        assert len(data) == len(LOCATORS)
        for row, loc in zip(data, LOCATORS):
            lat, lon = core.to_center_latlon(loc)
            assert row[0] == loc
            assert float(row[1]) == pytest.approx(lat, abs=tol)
            assert float(row[2]) == pytest.approx(lon, abs=tol)
        return
    if op == "bbox":
        assert header == ["input", "min_lat", "min_lon", "max_lat", "max_lon"]
        assert len(data) == len(LOCATORS)
        for row, loc in zip(data, LOCATORS):
            min_lat, min_lon, max_lat, max_lon = core.to_bbox(loc)
            assert row[0] == loc
            assert float(row[1]) == pytest.approx(min_lat, abs=tol)
            assert float(row[2]) == pytest.approx(min_lon, abs=tol)
            assert float(row[3]) == pytest.approx(max_lat, abs=tol)
            assert float(row[4]) == pytest.approx(max_lon, abs=tol)
        return
    if op == "contains-point":
        assert header == ["contains"]
        assert len(data) == len(LOCATORS)
        assert all(row[0] == "true" for row in data)
        return
    if op == "intersects-polygon":
        assert header == ["intersects"]
        assert len(data) == len(LOCATORS)
        assert all(row[0] == "true" for row in data)
        return
    if op == "neighbors":
        assert header == ["input", "neighbor"]
        expected: list[list[str]] = []
        for loc in LOCATORS:
            for neighbor in core.neighbors(loc, ring=1, diagonals=True):
                expected.append([loc, neighbor.locator])
        assert data == expected
        return
    if op == "adjacent":
        assert header == ["input", "direction", "locator"]
        expected = []
        for loc in LOCATORS:
            for direction, neighbor in core.adjacent(loc, diagonals=True).items():
                expected.append([loc, direction, neighbor.locator])
        assert data == expected
        return
    if op == "corners":
        assert header == ["input", "lat", "lon"]
        expected = []
        for loc in LOCATORS:
            nw, ne, sw, se = core.corners(loc)
            expected.extend(
                [
                    [loc, f"{nw[0]:.17g}", f"{nw[1]:.17g}"],
                    [loc, f"{ne[0]:.17g}", f"{ne[1]:.17g}"],
                    [loc, f"{sw[0]:.17g}", f"{sw[1]:.17g}"],
                    [loc, f"{se[0]:.17g}", f"{se[1]:.17g}"],
                ]
            )
        assert data == expected
        return
    if op == "precision":
        assert header == ["input", "precision"]
        expected = [[loc, str(core.precision_of(loc))] for loc in LOCATORS]
        assert data == expected
        return
    if op == "parent":
        assert header == ["input", "locator"]
        expected = [[loc, core.parent(loc).locator] for loc in LOCATORS]
        assert data == expected
        return
    if op == "children":
        assert header == ["input", "child"]
        expected = []
        for loc in LOCATORS:
            for child in core.children(loc):
                expected.append([loc, child.locator])
        assert data == expected
        return
    if op == "size":
        assert header == ["input", "width", "height"]
        assert len(data) == len(LOCATORS)
        for row, loc in zip(data, LOCATORS):
            width, height = core.cell_size(loc, unit="deg")
            assert row[0] == loc
            assert float(row[1]) == pytest.approx(width, abs=tol)
            assert float(row[2]) == pytest.approx(height, abs=tol)
        return
    if op == "area":
        assert header == ["input", "area_km2"]
        assert len(data) == len(LOCATORS)
        for row, loc in zip(data, LOCATORS):
            expected = core.area_km2(loc, method="spherical")
            assert row[0] == loc
            assert float(row[1]) == pytest.approx(expected, abs=tol)
        return
    if op == "diagonal":
        assert header == ["input", "diagonal_km"]
        assert len(data) == len(LOCATORS)
        for row, loc in zip(data, LOCATORS):
            expected = core.diagonal_km(loc, method="spherical")
            assert row[0] == loc
            assert float(row[1]) == pytest.approx(expected, abs=tol)
        return
    if op == "utm":
        assert header == ["input", "utm_zone"]
        expected = [[loc, core.to_utm_zone(loc)] for loc in LOCATORS]
        assert data == expected
        return
    if op == "geojson":
        assert header == ["input", "geojson"]
        assert len(data) == len(LOCATORS)
        for row, loc in zip(data, LOCATORS):
            assert row[0] == loc
            payload = json.loads(row[1])
            assert payload == core.to_geojson_feature(loc)
        return
    raise AssertionError(f"Unhandled op: {op}")
