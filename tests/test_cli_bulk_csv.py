def _find_native_cli() -> Path | None:
    env_path = os.environ.get("MAIDENHEAD_CLI_PATH")
    candidates: list[Path] = []
    if env_path:
        candidates.append(Path(env_path))
    for name in ("mh", "mh_cli"):
        resolved = shutil.which(name)
        if resolved:
            candidates.append(Path(resolved))
    candidates.extend(
        [
            ROOT / "build" / "mh_cli_staging" / "mh",
            ROOT / "build" / "mh_cli_staging" / "mh_cli",
            ROOT / "cmake-build-native-313" / "mh_cli",
            ROOT / "cmake-build-debug" / "mh_cli",
            ROOT / "cmake-build-default" / "mh_cli",
        ]
    )
    candidates.extend(Path(path) for path in ROOT.glob("cmake-build-native-*/mh_cli"))
    candidates.extend(Path(path) for path in ROOT.glob("build/temp.*/*/mh_cli"))
    valid = [path for path in candidates if path.is_file() and os.access(path, os.X_OK)]
    if not valid:
        return None
    return max(valid, key=lambda p: p.stat().st_mtime)


def _run_cli(args: list[str], stdin: str | None = None) -> subprocess.CompletedProcess[str]:
    cli_path = _find_native_cli()
    if cli_path is None:
        raise RuntimeError("native CLI not found; set MAIDENHEAD_CLI_PATH or build mh_cli")
    return subprocess.run(
        [str(cli_path), *args],
        input=stdin,
        text=True,
        capture_output=True,
    )


def _run_bulk_csv(
    tmp_path: Path,
    op: str,
    lines: list[str],
    extra_args: list[str] | None = None,
) -> list[list[str]]:
    file_path = tmp_path / f"bulk_{op}.txt"
    file_path.write_text("\n".join(lines))
    args = ["bulk", op, "--file", str(file_path), "--format", "csv"]
    if extra_args:
        args.extend(extra_args)
    proc = _run_cli(args)
    assert proc.returncode == 0, proc.stderr
    reader = csv.reader(io.StringIO(proc.stdout))
    return list(reader)


def _center_point_lines(locators: list[str]) -> list[str]:
    lines: list[str] = []
    for loc in locators:
        lat, lon = core.to_center_latlon(loc)
        lines.append(f"{loc} {lat:.17g} {lon:.17g}")
    return lines


def _bbox_polygon_lines(locators: list[str]) -> list[str]:
    lines: list[str] = []
    for loc in locators:
        min_lat, min_lon, max_lat, max_lon = core.to_bbox(loc)
        points = [
            f"{min_lat:.17g},{min_lon:.17g}",
            f"{min_lat:.17g},{max_lon:.17g}",
            f"{max_lat:.17g},{max_lon:.17g}",
            f"{max_lat:.17g},{min_lon:.17g}",
        ]
        lines.append(f"{loc} " + " ".join(points))
    return lines


